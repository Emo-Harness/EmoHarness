"""Rendering ``docs/preregistration.md`` from the artifacts it freezes (ADR-0012).

The document is generated, never hand-written, so the hashes in it always match
the files on disk. Nothing here carries a timestamp: the same inputs render the
same bytes, which is what makes the ``prereg-v1`` tag verifiable after the fact.
"""

from __future__ import annotations

import importlib.resources
from collections.abc import Mapping
from pathlib import Path
from typing import Final

from emoharness.common.errors import ValidationError
from emoharness.common.hashing import sha256_file, sha256_text, stable_hash
from emoharness.data.splits import read_subset
from emoharness.harness.loader import load_bundle
from emoharness.runner.context import RunContext
from emoharness.runner.paths import ProjectPaths, guard_write

HANDCRAFTED_PACKAGE: Final = 'emoharness.baselines'
HANDCRAFTED_RESOURCE: Final = 'handcrafted_prompt.md'

_TEMPLATE: Final = """# EmoHarness pre-registration

Generated by `examples/preregister.py`. Committed and tagged `prereg-v1` before
the first Builder round (ADR-0012). Any later change is an amendment carrying a
date and a reason, never a silent edit.

## Primary metric

Recognition score (Rec-S), macro-averaged over tasks within a group: seen
(ER-Lab, ER-Wild, SA) and held-out (Noise-ER, FG-ER, ML-ER, FG-SA, IR). CoT-S,
Rea-S, Avg Step, and multi-label precision, recall, and F1 are secondary and
descriptive.

## Hypotheses

| Id | Statement | Rows | Items | Test |
|---|---|---|---|---|
| H1 seen improvement | Rec-S(L5) - Rec-S(L0) > 0 on seen macro | L0, L5 | full seen (3,900) | 95% paired bootstrap CI excludes 0 |
| H2 held-out transfer | Rec-S(L5) - Rec-S(L0) > 0 on held-out macro | L0, L5 | full held-out (2,600) | CI excludes 0; per-task point estimates reported, negative ones included |
| H-B Builder gain | Rec-S(L5) - Rec-S(L3) > 0 on seen macro and on held-out macro | L3, L5 | full | CI excludes 0 for each group separately |
| H3 gap closed | Gap Closed = (Rec-S(L5) - Rec-S(L0)) / (Rec-S(L6) - Rec-S(L0)) on overall macro | L0, L5, L6 | subset (1,000), paired | tier 1 >= 0.25, tier 2 >= 0.5; the tier reached is reported with its CI |
| H4 generality | exploratory, no threshold | Qwen3-VL-4B-Instruct with and without L5 | subset | descriptive |

Teacher Performance Retained is reported descriptively, next to the baseline's
own value, so a reader sees how much of it the baseline already had.

## The ladder

Each rung adds one ingredient to the rung below (ADR-0009), so adjacent
differences isolate one effect: modality gain = L1 - L0, format gain = L2 - L1,
scaffold gain = L3 - L2, Builder gain = L5 - L3, total gain = L5 - L0.

{ladder}

## Analysis plan

ADR-0013: the unit is the benchmark item; every comparison is paired on
identical item sets with identical cached inputs; 95% paired bootstrap over
items with 10,000 resamples, resampling within task; macro averages recomputed
inside each resample; Holm-adjusted bootstrap p-values across the pre-registered
tests; differences below the judge noise floor reported without interpretation.

## Frozen artifacts

| Artifact | SHA-256 |
|---|---|
{artifacts}

### Configuration files

| File | SHA-256 |
|---|---|
{configs}

## Information firewall

1. No person opens a benchmark item, a benchmark-derived cache, or a model
   output on a benchmark item until `harness-frozen`.
2. Benchmark Target runs happen only after the freeze, except the Qwen3-VL-4B-Instruct
   calibration run, whose per-item outputs are not inspected.
3. Construction artifacts contain no benchmark ids; a test greps for every one.
4. After `harness-frozen`, harness files change only to fix crashes in I/O or
   serving, and each patch is recorded under `results/post_freeze_patches/`.
5. Every pre-registered test is reported whatever its outcome, including
   per-task negative transfer.
"""


def handcrafted_prompt_text() -> str:
    """The frozen L2 prompt, read from the package it ships in."""
    resource = importlib.resources.files(HANDCRAFTED_PACKAGE).joinpath(
        HANDCRAFTED_RESOURCE
    )
    return resource.read_text(encoding='utf-8')


def config_hashes(configs: Path) -> Mapping[str, str]:
    """Every committed config file's digest, keyed by its path inside ``configs/``."""
    return {
        path.relative_to(configs).as_posix(): sha256_file(path)
        for path in sorted(configs.rglob('*'))
        if path.is_file()
    }


def _require_files(paths: ProjectPaths) -> Mapping[str, Path]:
    required = {
        'benchmark manifest (`data/manifests/mme_emotion.jsonl`)': (
            paths.benchmark_manifest
        ),
        'external manifest (`data/manifests/external.jsonl`)': paths.external_manifest,
        'external splits (`data/splits/external_splits.json`)': paths.external_splits,
        'leakage report (`data/checksums/leakage_report.json`)': paths.leakage_report,
        'pre-registered subset (`data/splits/subset_1000.json`)': paths.subset,
    }
    missing = tuple(str(path) for path in required.values() if not path.is_file())
    if missing:
        raise ValidationError(
            'cannot pre-register before these artifacts exist: ' + ', '.join(missing)
        )
    return required


def artifact_hashes(ctx: RunContext) -> Mapping[str, str]:
    """The SHA-256 of everything the pre-registration freezes."""
    paths = ctx.paths
    required = _require_files(paths)
    digests = {
        name: sha256_file(path)
        for name, path in required.items()
        if name != 'pre-registered subset (`data/splits/subset_1000.json`)'
    }
    return {
        'subset id list (order-independent)': read_subset(paths.subset).subset_hash,
        **digests,
        'Stage 1 harness bundle (content hash)': load_bundle(
            paths.bundle
        ).content_hash(),
        'L2 handcrafted prompt': sha256_text(handcrafted_prompt_text()),
        'configs/ (all files)': stable_hash(config_hashes(paths.configs)),
    }


def _table(rows: Mapping[str, str]) -> str:
    return '\n'.join(f'| {name} | `{value}` |' for name, value in rows.items())


def _ladder_table(ctx: RunContext) -> str:
    header = (
        '| Rung | Method | Items | Calls | Priority |\n| --- | --- | --- | --- | --- |'
    )
    lines = [
        f'| {row.name} | {row.method} | {row.item_set} | '
        f'{row.calls if row.calls is not None else "-"} | {row.priority} |'
        for row in ctx.ladder.rows.values()
    ]
    return '\n'.join([header, *lines])


def build_preregistration(ctx: RunContext) -> str:
    """Render the pre-registration document. Deterministic in its inputs."""
    return _TEMPLATE.format(
        ladder=_ladder_table(ctx),
        artifacts=_table(artifact_hashes(ctx)),
        configs=_table(config_hashes(ctx.paths.configs)),
    )


def write_preregistration(path: Path, text: str, force: bool = False) -> Path:
    """Write the rendered document, refusing to clobber an existing one."""
    target = guard_write(path, force)
    target.write_text(text, encoding='utf-8')
    return target
